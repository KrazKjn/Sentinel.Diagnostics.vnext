            "const" or
            "continue" or
            "decimal" or
            "default" or
            "delegate" or
            "do" or
            "double" or
            "else" or
            "enum" or
            "event" or
            "explicit" or
            "extern" or
            "false" or
            "finally" or
            "fixed" or
            "float" or
            "for" or
            "foreach" or
            "goto" or
            "if" or
            "implicit" or
            "in" or
            "int" or
            "interface" or
            "internal" or
            "is" or
            "lock" or
            "long" or
            "namespace" or
            "new" or
            "null" or
            "object" or
            "operator" or
            "out" or
            "override" or
            "params" or
            "private" or
            "protected" or
            "public" or
            "readonly" or
            "ref" or
            "return" or
            "sbyte" or
            "sealed" or
            "short" or
            "sizeof" or
            "stackalloc" or
            "static" or
