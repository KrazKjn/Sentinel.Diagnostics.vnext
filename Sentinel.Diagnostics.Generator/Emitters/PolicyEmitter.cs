            _ => false
        };
    }

    private static string ToLiteral(string value)
    {
        return Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(
            value,
            quote: true);
    }

    private static string ToBooleanLiteral(bool value)
    {
        return value ? "true" : "false";
    }
}